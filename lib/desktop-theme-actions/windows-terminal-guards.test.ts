import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

import {
  context,
  decodeCommand,
  importAction,
  readReply,
  runManagedComputerSsh,
  SETTINGS,
  STABLE_PATH,
  PREVIEW_PATH,
} from "./windows-terminal.fixtures";

beforeEach(() => {
  runManagedComputerSsh.mockReset();
});

afterEach(() => {
  vi.restoreAllMocks();
  vi.resetModules();
});

describe("windowsTerminalAction", () => {
  it("does not write when the colour is already set", async () => {
    const action = await importAction();
    const already = SETTINGS.replace(
      `"name": "Windows PowerShell"`,
      `"name": "Windows PowerShell",\n                "tabColor": "#2F5F87"`,
    );
    runManagedComputerSsh.mockResolvedValueOnce(readReply([{ content: already, path: STABLE_PATH }]));

    await action.run(context("#2F5F87"));

    // Writing is what makes Terminal reload; a reload nobody asked for is a
    // visible flicker in every open window.
    expect(runManagedComputerSsh).toHaveBeenCalledTimes(1);
  });

  it("still updates the other installs when one is already correct", async () => {
    const action = await importAction();
    const already = SETTINGS.replace(
      `"name": "Windows PowerShell"`,
      `"name": "Windows PowerShell",\n                "tabColor": "#2F5F87"`,
    );
    runManagedComputerSsh
      .mockResolvedValueOnce(readReply([
        { content: already, path: STABLE_PATH },
        { content: SETTINGS, path: PREVIEW_PATH },
      ]))
      .mockResolvedValue({ stderr: "", stdout: "" });

    await action.run(context("#2F5F87"));

    expect(runManagedComputerSsh).toHaveBeenCalledTimes(2);
    expect(decodeCommand(runManagedComputerSsh.mock.calls[1][1])).toContain(JSON.stringify(PREVIEW_PATH));
  });

  it("keeps going when one install throws", async () => {
    const action = await importAction();
    const errors = vi.spyOn(console, "error").mockImplementation(() => {});
    runManagedComputerSsh
      .mockResolvedValueOnce(readReply([
        { content: SETTINGS, path: STABLE_PATH },
        { content: SETTINGS, path: PREVIEW_PATH },
      ]))
      .mockRejectedValueOnce(new Error("access denied"))
      .mockResolvedValue({ stderr: "", stdout: "" });

    await expect(action.run(context())).resolves.toBeUndefined();

    // The one that matters may well be the one after the failure.
    expect(runManagedComputerSsh).toHaveBeenCalledTimes(3);
    expect(decodeCommand(runManagedComputerSsh.mock.calls[2][1])).toContain(JSON.stringify(PREVIEW_PATH));
    expect(errors).toHaveBeenCalled();
  });

  it("falls back to the whitespace nudge when there is no PowerShell profile", async () => {
    const action = await importAction();
    const noPowerShell = `{ "profiles": { "list": [ { "name": "Command Prompt", "commandline": "cmd.exe" } ] } }`;
    runManagedComputerSsh
      .mockResolvedValueOnce(readReply([{ content: noPowerShell, path: STABLE_PATH }]))
      .mockResolvedValue({ stderr: "", stdout: "" });

    await action.run(context());

    expect(runManagedComputerSsh).toHaveBeenCalledTimes(2);
    const nudge = decodeCommand(runManagedComputerSsh.mock.calls[1][1]);
    expect(nudge).toContain("WriteAllBytes");
    expect(nudge).toContain(JSON.stringify(STABLE_PATH));
    expect(nudge).not.toContain("FromBase64String");
  });

  it("does nothing when Terminal is not installed", async () => {
    const action = await importAction();
    runManagedComputerSsh.mockResolvedValueOnce({ stderr: "", stdout: "" });

    await action.run(context());
    expect(runManagedComputerSsh).toHaveBeenCalledTimes(1);
  });

  it("refuses to rewrite an implausibly large settings file", async () => {
    const action = await importAction();
    const errors = vi.spyOn(console, "error").mockImplementation(() => {});
    const huge = SETTINGS.replace("// generated by Windows Terminal", `// ${"x".repeat(70 * 1024)}`);
    runManagedComputerSsh.mockResolvedValueOnce(readReply([{ content: huge, path: STABLE_PATH }]));

    await action.run(context());

    expect(runManagedComputerSsh).toHaveBeenCalledTimes(1);
    expect(errors).toHaveBeenCalled();
  });

  it("never sends the file itself, so the command line cannot overflow", async () => {
    const action = await importAction();
    // cmd.exe caps the command line at 8191 characters; base64'ing a file this
    // size into the command would be several times that.
    const big = SETTINGS.replace("// generated by Windows Terminal", `// ${"padding ".repeat(1200)}`);
    expect(big.length).toBeGreaterThan(8191);

    runManagedComputerSsh
      .mockResolvedValueOnce(readReply([{ content: big, path: STABLE_PATH }]))
      .mockResolvedValue({ stderr: "", stdout: "" });

    await action.run(context());

    // The read reply carries the file, but the commands we send must not.
    for (const [, command] of runManagedComputerSsh.mock.calls) {
      expect(command.length).toBeLessThan(8000);
    }
  });

  it("asks for all three settings locations on the read", async () => {
    const action = await importAction();
    runManagedComputerSsh.mockResolvedValueOnce({ stderr: "", stdout: "" });

    await action.run(context());
    const read = decodeCommand(runManagedComputerSsh.mock.calls[0][1]);
    expect(read).toContain("Microsoft.WindowsTerminal_8wekyb3d8bbwe");
    expect(read).toContain("Microsoft.WindowsTerminalPreview_8wekyb3d8bbwe");
    expect(read).toContain("Microsoft\\Windows Terminal\\settings.json");
  });

  it("signs on the highlight colour, so a recolour re-fires it", async () => {
    const action = await importAction();
    expect(action.signature(context("#111111"))).not.toBe(action.signature(context("#222222")));
  });
});
